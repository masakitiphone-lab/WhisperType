pub(super) fn modifier_flag_value(modifier: &str) -> Result<u64, String> {
    match modifier {
        "Ctrl" => Ok(0x0004_0000),
        "Shift" => Ok(0x0002_0000),
        "Alt" => Ok(0x0008_0000),
        "Meta" => Ok(0x0010_0000),
        other => Err(format!("Unsupported macOS modifier: {}", other)),
    }
}

