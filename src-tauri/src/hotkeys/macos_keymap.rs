pub(super) fn mouse_to_macos_button(value: &str) -> Result<u32, String> {
    let upper = value.to_uppercase();
    let button = match upper.as_str() {
        "MOUSELEFT" => 0,
        "MOUSERIGHT" => 1,
        "MOUSEMIDDLE" => 2,
        "MOUSE4" => 3,
        "MOUSE5" => 4,
        _ => return Err(format!("Unsupported macOS mouse button: {}", value)),
    };

    Ok(button)
}
